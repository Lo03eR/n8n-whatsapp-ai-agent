window.UU_LANG = localStorage.getItem("uu_lang") || "kz";

window.applyI18n = function (lang) {
  lang = lang || window.UU_LANG;
  window.UU_LANG = lang;
  localStorage.setItem("uu_lang", lang);
  const dict = window.I18N[lang] || window.I18N.kz;

  document.documentElement.setAttribute("lang", lang === "kz" ? "kk" : "ru");

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const v = dict[el.getAttribute("data-i18n")];
    if (v != null) el.textContent = v;
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const v = dict[el.getAttribute("data-i18n-html")];
    if (v != null) el.innerHTML = v;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const v = dict[el.getAttribute("data-i18n-ph")];
    if (v != null) el.setAttribute("placeholder", v);
  });

  document.querySelectorAll(".lang-switch button").forEach(b => {
    b.classList.toggle("active", b.dataset.lang === lang);
  });
};

